def _record(pid: int, port: int = 4242, started_at: str = "2026-10-08T10:00:00+00:00") -> DiscoveryRecord:
    return DiscoveryRecord(
        port=port,
        pid=pid,
        protocol=str(PROTOCOL_VERSION),
        backend_version=__version__,
        token="secret-" + "z" * 36,
        started_at=started_at,
    )


def _dead_pid() -> int:
    proc = subprocess.Popen([sys.executable, "-c", "pass"])
    proc.wait()
    return proc.pid


