# --- a real backend process -----------------------------------------------------------------------------


def _spawn_backend(runtime_root: Path) -> subprocess.Popen:
    env = dict(os.environ)
    env.pop("COYPU_BUILDER_TOKEN", None)
    for name in ("LOCALAPPDATA", "XDG_RUNTIME_DIR", "HOME", "USERPROFILE"):
        env[name] = str(runtime_root)
    flags = subprocess.CREATE_NEW_PROCESS_GROUP if ON_WINDOWS else 0
    return subprocess.Popen(
        [sys.executable, "-m", "coypu_builder", "serve", "--port", "0"],
        stdin=subprocess.DEVNULL,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        env=env,
        text=True,
        creationflags=flags,
    )


def _stop_cleanly(proc: subprocess.Popen) -> None:
    proc.send_signal(signal.CTRL_BREAK_EVENT if ON_WINDOWS else signal.SIGTERM)


def _hello_sync(url: str, token: str) -> Envelope:
    with sync_connect(url) as ws:
        req = Envelope(
            v=PROTOCOL_VERSION,
            id="1",
            type="req",
            method="session.hello",
            params={"client": "pytest", "client_version": "0", "token": token},
        )
        ws.send(encode_frame(req))
        reply, _tail = decode_frame(ws.recv())
        return reply


def test_cli_serve_end_to_end(runtime_root):
    proc = _spawn_backend(runtime_root)
    watchdog = threading.Timer(90, proc.kill)
    watchdog.start()
    try:
        line = proc.stdout.readline()
        started = json.loads(line)
        assert set(started) == {"port", "token", "pid", "protocol"}
        assert started["protocol"] == str(PROTOCOL_VERSION)
        token = started["token"]
        # Booleans only below: a failing assertion would otherwise print the token.
        long_enough = len(token) >= 43  # secrets.token_urlsafe(32)
        assert long_enough
        differs_from_the_test_token = TOKEN != token
        assert differs_from_the_test_token
        records = discovery.live_records()
        assert len(records) == 1
        record = records[0]
        same_port, same_pid = record.port == started["port"], record.pid == started["pid"]
        same_token = record.token == token
        assert same_port
        assert same_pid
        assert same_token
        assert record.protocol == str(PROTOCOL_VERSION)
        assert record.backend_version == __version__

        url = f"ws://127.0.0.1:{started['port']}"
        accepted = _hello_sync(url, token).type == "res"
        assert accepted
        refused = _hello_sync(url, "not-the-token")
        assert refused.type == "err"
        assert refused.error.code == "E_UNAUTHORIZED"

        _stop_cleanly(proc)
        assert proc.wait(timeout=30) == 0
        assert not (discovery.runtime_dir() / f"backend-{started['pid']}.json").exists()
        assert discovery.live_records() == []

        rest = proc.stdout.read()
        stderr = proc.stderr.read()
        leaked_stdout, leaked_stderr = token in rest, token in stderr
        leaked_args = token in " ".join(proc.args)
        assert not leaked_stdout
        assert not leaked_stderr
        assert not leaked_args
        assert "--token" not in proc.args
    finally:
        watchdog.cancel()
        if proc.poll() is None:
            proc.kill()
            proc.wait()
        proc.stdout.close()
        proc.stderr.close()


