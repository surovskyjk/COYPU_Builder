@pytest.mark.skipif(not ON_WINDOWS, reason="Windows ACLs")
def test_windows_acl_names_only_the_user_and_the_system_accounts(runtime_root):
    path = discovery.write_record(_record(os.getpid()))
    allowed = {os.environ["USERNAME"].lower(), "system", "administrators", "owner rights", "creator owner"}
    for target in (path.parent, path):
        acl = subprocess.run(["icacls", str(target)], capture_output=True, text=True, check=True).stdout
        principals = set()
        for line in acl.splitlines():
            if ":(" in line:
                name = line.split(":(")[0].replace(str(target), "").strip()
                principals.add(name.split("\\")[-1].lower())
        assert principals, acl
        assert principals <= allowed, acl
    assert (
        "(I)"
        not in subprocess.run(["icacls", str(path.parent)], capture_output=True, text=True, check=True).stdout
    ), "the directory must not inherit its ACL"


def _acl_principals(target: Path) -> tuple[set[str], bool]:
    acl = subprocess.run(["icacls", str(target)], capture_output=True, text=True, check=True).stdout
    principals = set()
    for line in acl.splitlines():
        if ":(" in line:
            name = line.split(":(")[0].replace(str(target), "").strip()
            principals.add(name.split("\\")[-1].lower())
    return principals, ":(I)" in acl


@pytest.mark.skipif(not ON_WINDOWS, reason="Windows ACLs")
def test_an_existing_directory_with_an_inherited_acl_is_made_protected(runtime_root):
    base = runtime_root / "COYPU Builder" / "runtime"
    base.mkdir(parents=True)  # default mode: the ACL is inherited from the parent
    discovery._acl_verified.discard(base)
    assert _acl_principals(base)[1], "precondition: the pre-existing directory inherits its ACL"
    assert discovery.runtime_dir() == base
    principals, inherits = _acl_principals(base)
    assert not inherits
    assert os.environ["USERNAME"].lower() in principals
    assert principals <= {os.environ["USERNAME"].lower(), "system", "administrators", "owner rights"}
    # Still usable by us.
    discovery.write_record(_record(os.getpid()))
    assert len(discovery.live_records()) == 1


