def test_every_method_declares_a_tier_and_only_the_session_pair_is_stable():
    assert METHODS
    for spec in METHODS:
        assert isinstance(spec.stability, Stability), spec.name
    stable = {spec.name for spec in METHODS if spec.stability is Stability.STABLE}
    assert stable == {"session.hello", "session.ping"}
    assert {s.stability for s in METHODS if s.name not in stable} == {Stability.EXPERIMENTAL}
    assert next(s for s in METHODS if s.name == "alignment.envelope").stability is Stability.EXPERIMENTAL


