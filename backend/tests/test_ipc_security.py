async def test_tokens_are_compared_with_hmac_compare_digest(token_server, monkeypatch):
    calls: list[tuple[bytes, bytes]] = []
    real = handlers.hmac.compare_digest

    def spy(a, b):
        calls.append((a, b))
        return real(a, b)

    monkeypatch.setattr(handlers.hmac, "compare_digest", spy)
    async with connect(token_server) as ws:
        await _call(ws, "1", "session.hello", _hello("wrong"))
        await _call(ws, "2", "session.hello", _hello(TOKEN))
    assert [c[1] for c in calls] == [b"wrong", TOKEN.encode()]


