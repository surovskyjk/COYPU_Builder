def _spawn_backend_with_unusable_runtime(blocker: Path) -> subprocess.Popen:
    blocker.write_text("not a directory", encoding="utf-8")
    return _spawn_backend(blocker)


def test_serve_still_serves_when_the_discovery_record_cannot_be_written(tmp_path):
    """Spawn mode takes the token over the pipe, so an unusable runtime directory only costs external
    attach: the startup line is printed and `session.hello` answered, with one warning on stderr."""
    proc = _spawn_backend_with_unusable_runtime(tmp_path / "blocker")
    watchdog = threading.Timer(90, proc.kill)
    watchdog.start()
    try:
        started = json.loads(proc.stdout.readline())
        assert set(started) == {"port", "token", "pid", "protocol"}
        accepted = _hello_sync(f"ws://127.0.0.1:{started['port']}", started["token"]).type == "res"
        assert accepted
        _stop_cleanly(proc)
        assert proc.wait(timeout=30) == 0
        stderr = proc.stderr.read()
        leaked = started["token"] in stderr
        assert not leaked
        assert stderr.count("discovery record skipped") == 1
        assert "None" not in stderr
    finally:
        watchdog.cancel()
        if proc.poll() is None:
            proc.kill()
            proc.wait()
        proc.stdout.close()
        proc.stderr.close()


