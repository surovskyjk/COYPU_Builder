    base = runtime_root / "COYPU Builder" / "runtime"
    base.mkdir(parents=True, mode=0o700)  # protected, like a fresh one
    subprocess.run(["icacls", str(base), "/grant", "Everyone:(OI)(CI)R"], check=True, capture_output=True)
