def test_no_token_flag_appears_in_the_client_or_the_tools():
    repo = Path(__file__).resolve().parents[2]
    needles = ("--back" + "end-token", "--to" + "ken")
    skip_dirs = {".godot", "godot", "addons", "reports", "__pycache__", "captures"}
    offenders: list[str] = []
    for top in ("client", "tools"):
        for path in (repo / top).rglob("*"):
            if not path.is_file() or skip_dirs & set(path.relative_to(repo).parts):
                continue
            if path.suffix.lower() not in {
                ".gd",
                ".ps1",
                ".py",
                ".md",
                ".json",
                ".tscn",
                ".cfg",
                ".sh",
                ".yml",
            }:
                continue
            text = path.read_text(encoding="utf-8", errors="ignore")
            offenders.extend(f"{path.relative_to(repo)}: {n}" for n in needles if n in text)
    assert offenders == []
